"""Validate stage10/project_tracker.json and compute task-based progress (read-only unless --write-roadmap).

  python -m stage10.tools.project_tracker --check          # validate tracker + roadmap progress block is current
  python -m stage10.tools.project_tracker --progress       # print progress
  python -m stage10.tools.project_tracker --write-roadmap  # regenerate the progress block in PROJECT_ROADMAP.md

A task is actionable when it is not blocked/deferred/implemented and its dependencies are implemented or verified
(a review gate can start once the work it reviews is implemented). Milestone status is complete / in_progress / not_started;
blocked tasks are reported separately (a milestone waiting on dependencies is not "blocked").

Progress is counted from explicit task checklists: verified / required tasks, with implementation progress reported
separately. Tasks are NOT effort-weighted (no weighting has been defined), so percentages are task counts, not effort.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TRACKER = ROOT / "stage10" / "project_tracker.json"
ROADMAP = ROOT / "stage10" / "PROJECT_ROADMAP.md"
BEGIN, END = "<!-- PROGRESS:BEGIN (generated by stage10/tools/project_tracker.py; do not edit by hand) -->", "<!-- PROGRESS:END -->"
TASK_STATUS = {"not_started", "in_progress", "blocked", "implemented", "verified", "deferred"}
LANG_STATUS = TASK_STATUS | {"not_applicable"}
BACKLOG_STATUS = {"proposed", "evaluated", "approved", "deferred", "rejected"}
SCOPES = {"required", "proposed_target", "future_enhancement"}
PRIORITY_ORDER = {"P0": 0, "P1": 1, "P2": 2}
TASK_KEYS = {"task_id", "milestone_id", "name", "description", "status", "priority", "dependencies", "acceptance_criteria",
             "verification_evidence", "blockers", "decisions_required", "files_affected", "completion_date", "next_action", "release_scope"}


def load(path: Path = TRACKER) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def validate(t: dict) -> list[str]:
    err = []
    ms = {m["milestone_id"]: m for m in t["milestones"]}
    tasks = {}
    for x in t["tasks"]:
        tid = x.get("task_id", "?")
        if set(x) != TASK_KEYS:
            err.append(f"{tid}: keys differ from the task schema: missing {sorted(TASK_KEYS - set(x))} extra {sorted(set(x) - TASK_KEYS)}")
            continue
        if tid in tasks:
            err.append(f"{tid}: duplicate task id")
        tasks[tid] = x
        if not re.fullmatch(r"M[1-8]-[A-Z0-9]+", tid) or x["milestone_id"] != tid.split("-")[0] or x["milestone_id"] not in ms:
            err.append(f"{tid}: bad id or milestone")
        if x["status"] not in TASK_STATUS:
            err.append(f"{tid}: unknown status {x['status']}")
        if x["priority"] not in PRIORITY_ORDER or x["release_scope"] not in SCOPES:
            err.append(f"{tid}: bad priority or release_scope")
        if not x["acceptance_criteria"]:
            err.append(f"{tid}: no acceptance criteria")
        if x["status"] == "verified":
            if not x["verification_evidence"] or not x["completion_date"]:
                err.append(f"{tid}: verified without evidence or completion_date")
            if x["blockers"]:
                err.append(f"{tid}: verified but has blockers")
        elif x["completion_date"]:
            err.append(f"{tid}: completion_date set but status is {x['status']}")
        if x["status"] == "implemented" and not x["verification_evidence"]:
            err.append(f"{tid}: implemented without any evidence")
        if x["status"] == "blocked" and not x["blockers"]:
            err.append(f"{tid}: blocked without a stated blocker")
        if x["status"] != "verified" and not x["next_action"]:
            err.append(f"{tid}: open task without next_action")
        if x["completion_date"]:
            try:
                date.fromisoformat(x["completion_date"])
            except ValueError:
                err.append(f"{tid}: bad completion_date")
        for e in x["verification_evidence"]:
            if set(e) != {"type", "ref", "result", "date"} or e["type"] not in {"test", "command", "file", "review"}:
                err.append(f"{tid}: malformed evidence {e}")
            elif e["type"] == "test" and not (ROOT / e["ref"].split("::")[0]).exists():
                err.append(f"{tid}: evidence test file missing: {e['ref']}")
        if x["status"] in ("implemented", "verified"):
            for f in x["files_affected"]:
                if not (ROOT / f).exists():
                    err.append(f"{tid}: affected file does not exist: {f}")
    for tid, x in tasks.items():
        for d in x["dependencies"]:
            if d not in tasks:
                err.append(f"{tid}: unknown dependency {d}")
            elif x["status"] == "verified" and tasks[d]["status"] != "verified":
                err.append(f"{tid}: verified while dependency {d} is {tasks[d]['status']}")
    # cycles
    state = {}

    def visit(n, stack):
        if state.get(n) == 1:
            err.append(f"dependency cycle: {' -> '.join(stack + [n])}")
            return
        if state.get(n) == 2 or n not in tasks:
            return
        state[n] = 1
        for d in tasks[n]["dependencies"]:
            visit(d, stack + [n])
        state[n] = 2
    for n in tasks:
        visit(n, [])
    # milestones: declared status must equal computed
    prog = progress(t)
    for m in t["milestones"]:
        c = prog["milestones"][m["milestone_id"]]["computed_status"]
        if m["declared_status"] != c:
            err.append(f"{m['milestone_id']}: declared_status {m['declared_status']} != computed {c}")
        if m["declared_status"] == "complete" and not m["approved_by_owner"]:
            err.append(f"{m['milestone_id']}: complete without owner approval")
    # languages
    crit = set(t["language_feature_criteria"])
    for lang in t["languages"]:
        if set(lang["features"]) != crit:
            err.append(f"language {lang['code']}: feature set differs from language_feature_criteria")
        for f, v in lang["features"].items():
            if v["status"] not in LANG_STATUS:
                err.append(f"language {lang['code']}.{f}: bad status")
            if v["status"] == "verified" and not v["evidence"]:
                err.append(f"language {lang['code']}.{f}: verified without evidence")
        if lang["release_scope"] not in SCOPES:
            err.append(f"language {lang['code']}: bad release_scope")
    # capabilities and backlog
    for c in t["capabilities"]:
        for d in c["requires_tasks"]:
            if d not in tasks:
                err.append(f"{c['capability_id']}: unknown task {d}")
    bl = {b["item_id"] for b in t["backlog"]}
    for b in t["backlog"]:
        if b["status"] not in BACKLOG_STATUS:
            err.append(f"{b['item_id']}: bad backlog status")
    for tid, x in tasks.items():
        for d in x["dependencies"]:
            if d in bl:
                err.append(f"{tid}: depends on backlog item {d} (backlog must not silently expand a milestone)")
    return err


def _pct(a, b):
    return f"{(100 * a / b):.0f}%" if b else "n/a"


def progress(t: dict) -> dict:
    tasks = {x["task_id"]: x for x in t["tasks"]}
    out = {"milestones": {}}
    for m in t["milestones"]:
        mid = m["milestone_id"]
        req = [x for x in t["tasks"] if x["milestone_id"] == mid and x["release_scope"] == "required"]
        ver = [x for x in req if x["status"] == "verified"]
        impl = [x for x in req if x["status"] in ("implemented", "verified")]
        blocked = [x for x in req if x["status"] == "blocked"]
        remaining = [x for x in req if x["status"] not in ("verified", "deferred")]
        deferred = [x for x in req if x["status"] == "deferred"]      # still required: they block completion until verified
        actionable = [x for x in remaining if x["status"] not in ("blocked", "deferred", "implemented")
                      and all(tasks.get(d, {}).get("status") in ("implemented", "verified") for d in x["dependencies"])]
        actionable.sort(key=lambda x: (PRIORITY_ORDER[x["priority"]], x["task_id"]))
        if req and len(ver) == len(req):
            st = "complete"
        elif any(x["status"] in ("in_progress", "implemented", "verified") for x in req):
            st = "in_progress"
        else:
            st = "not_started"
        out["milestones"][mid] = {
            "name": m["name"], "computed_status": st, "required": len(req), "verified": len(ver), "implemented_or_verified": len(impl),
            "blocked": [(x["task_id"], "; ".join(x["blockers"])) for x in blocked],
            "remaining": [x["task_id"] for x in remaining],
            "next_actionable": actionable[0]["task_id"] if actionable else None,
            "pending_review": [x["task_id"] for x in req if x["status"] == "implemented"],
            "deferred_required": [x["task_id"] for x in deferred],
            "unmet_criteria": {x["task_id"]: x["acceptance_criteria"] for x in remaining + deferred},
        }
    allreq = [x for x in t["tasks"] if x["release_scope"] == "required"]
    out["overall"] = {"milestones_complete": sum(v["computed_status"] == "complete" for v in out["milestones"].values()),
                      "milestones_total": len(t["milestones"]), "required_tasks": len(allreq),
                      "verified_tasks": sum(x["status"] == "verified" for x in allreq),
                      "implemented_or_verified_tasks": sum(x["status"] in ("implemented", "verified") for x in allreq),
                      "blocked_tasks": sum(x["status"] == "blocked" for x in allreq)}
    caps = []
    for c in t["capabilities"]:
        st = [tasks.get(d, {}).get("status") for d in c["requires_tasks"]]
        caps.append((c["capability_id"], c["name"], "verified" if all(s == "verified" for s in st) else
                     ("partially implemented" if any(s in ("implemented", "verified") for s in st) else "not available")))
    out["capabilities"] = caps
    langs = []
    for lang in t["languages"]:
        app = {f: v for f, v in lang["features"].items() if v["status"] != "not_applicable"}
        nv = sum(v["status"] == "verified" for v in app.values())
        ni = sum(v["status"] in ("implemented", "verified") for v in app.values())
        langs.append((lang["code"], lang["name"], lang["script"], lang["release_scope"], nv, ni, len(app),
                      "supported" if nv == len(app) else "NOT supported"))
    out["languages"] = langs
    out["backlog"] = [(b["item_id"], b["name"], b["status"]) for b in t["backlog"]]
    return out


def render(t: dict) -> str:
    p = progress(t)
    o = p["overall"]
    L = [BEGIN, "", f"_Computed from `stage10/project_tracker.json` (tracker updated {t['updated']}). Task counts are unweighted._", "",
         "### Overview", "",
         f"- Milestones complete (all required tasks verified): **{o['milestones_complete']} / {o['milestones_total']}**",
         f"- Required tasks verified: **{o['verified_tasks']} / {o['required_tasks']}** ({_pct(o['verified_tasks'], o['required_tasks'])}); "
         f"implemented or verified: {o['implemented_or_verified_tasks']} / {o['required_tasks']}; blocked: {o['blocked_tasks']}",
         f"- User-facing capabilities verified: **{sum(c[2] == 'verified' for c in p['capabilities'])} / {len(p['capabilities'])}**. "
         "Completed groundwork milestones are not application functionality.", "",
         "| Milestone | Status | Verified / required | Implemented or verified | Pending owner review | Blocked | Next actionable task |",
         "|---|---|---|---|---|---|---|"]
    for mid, m in p["milestones"].items():
        L.append(f"| {mid} {m['name']} | {m['computed_status']} | {m['verified']} / {m['required']} ({_pct(m['verified'], m['required'])}) | "
                 f"{m['implemented_or_verified']} / {m['required']} | {', '.join(m['pending_review']) or '-'} | "
                 f"{', '.join(b for b, _ in m['blocked']) or '-'} | {m['next_actionable'] or ('-' if not m['remaining'] else 'waiting on dependencies')} |")
    L += ["", "### Blocked tasks", ""]
    bl = [(b, r) for m in p["milestones"].values() for b, r in m["blocked"]]
    L += [f"- **{b}**: {r}" for b, r in bl] or ["- none"]
    L += ["", "### User-facing capabilities", "", "| ID | Capability | Status |", "|---|---|---|"]
    L += [f"| {c} | {n} | {s} |" for c, n, s in p["capabilities"]]
    L += ["", "### Languages (a language is supported only when every applicable feature is verified)", "",
          "| Code | Language | Script | Scope | Features verified | Implemented or verified | Claim |", "|---|---|---|---|---|---|---|"]
    L += [f"| {c} | {n} | {s} | {sc} | {v} / {a} | {i} / {a} | {cl} |" for c, n, s, sc, v, i, a, cl in p["languages"]]
    L += ["", "### Remaining required tasks and unmet acceptance criteria", ""]
    for mid, m in p["milestones"].items():
        if not m["remaining"] and not m["deferred_required"]:
            continue
        extra = f" + {len(m['deferred_required'])} deferred (required; blocks completion)" if m["deferred_required"] else ""
        L.append(f"<details><summary>{mid}: {len(m['remaining'])} remaining{extra}</summary>\n")
        for tid in m["remaining"]:
            L.append(f"- **{tid}**: " + "; ".join(m["unmet_criteria"][tid]))
        for tid in m["deferred_required"]:
            L.append(f"- **{tid}** (deferred): " + "; ".join(m["unmet_criteria"][tid]))
        L.append("\n</details>\n")
    L += ["", END]
    return "\n".join(L)


def roadmap_block_current(t: dict) -> bool:
    s = ROADMAP.read_text(encoding="utf-8")
    if BEGIN not in s or END not in s:
        return False
    return s[s.index(BEGIN): s.index(END) + len(END)] == render(t)


def write_roadmap(t: dict):
    s = ROADMAP.read_text(encoding="utf-8")
    s = s[: s.index(BEGIN)] + render(t) + s[s.index(END) + len(END):]
    ROADMAP.write_text(s, encoding="utf-8")


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--progress", action="store_true")
    ap.add_argument("--write-roadmap", action="store_true")
    a = ap.parse_args()
    t = load()
    errs = validate(t)
    if a.write_roadmap and not errs:
        write_roadmap(t)
    if a.progress:
        print(render(t))
    for e in errs:
        print("  ERROR", e)
    stale = not roadmap_block_current(t)
    if stale:
        print("  ERROR PROJECT_ROADMAP.md progress block is stale (run --write-roadmap)")
    ok = not errs and not stale
    print("STAGE10 PROJECT TRACKER:", "PASS" if ok else "FAIL")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
